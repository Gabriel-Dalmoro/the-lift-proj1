const CAR_TOP = 1007;
const BASELINE = 1259;

export default function Logo({
  className = "",
  title = "The Lift",
  cable = 120,
  rise = false,
  riseFrom = 520,
  duration = 2.4,
  delay = 0.2,
  clip = true,
  onRisen,
}: {
  className?: string;
  title?: string;
  /** How much cable shows above the cap height, in logo units. */
  cable?: number;
  /** Animate the "i" car rising from below into the word. */
  rise?: boolean;
  riseFrom?: number;
  duration?: number;
  delay?: number;
  /** false lets the cable run off the top and the car start below the box. */
  clip?: boolean;
  onRisen?: () => void;
}) {
  const reduce = useReducedMotion();
  const top = 941 - cable;
  const animate = rise && !reduce;

  return (
    <svg
      viewBox={`335 ${top} 832 ${BASELINE - top}`}
      className={className}
      role="img"
      aria-label={title}
      fill="currentColor"
      overflow={clip ? "hidden" : "visible"}
      style={clip ? undefined : { overflow: "visible" }}
    >
      <title>{title}</title>
      <path d={THE} fillRule="evenodd" />
      {/* L */}
      <rect x="622" y="941" width="62" height="318" />
      <rect x="622" y="1200" width="128" height="59" />
      {/* F */}
      <rect x="860" y="941" width="63" height="318" />
      <rect x="860" y="941" width="132" height="59" />
      <rect x="860" y="1068" width="127" height="59" />
      {/* T */}
      <rect x="1000" y="941" width="162" height="59" />
      <rect x="1049" y="941" width="63" height="318" />
      {/* i: the lift car and its cable */}
      <motion.g
        initial={animate ? { y: riseFrom } : false}
        animate={{ y: 0 }}
        transition={{ duration, delay, ease: [0.45, 0, 0.2, 1] }}
        onAnimationComplete={() => onRisen?.()}
      >
        <rect x="800" y={top - 6000} width="2" height={CAR_TOP - top + 6000} />
        <rect x="758" y={CAR_TOP} width="86" height="4" />
        <rect x="766" y="1024" width="71" height="235" />
      </motion.g>
    </svg>
  );
}
